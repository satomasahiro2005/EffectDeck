def header(type_name, members, hash_value, float_count=None):
    """dsp/generated/cpp/<type>Params.h と同じ形。"""
    if float_count is None:
        float_count = sum(c for _, c in members)
    body = "\n".join("  float %s%s;" % (n, "" if c == 1 else "[%d]" % c) for n, c in members)
    return (
        "// Generated by scripts/gen-dsp-params.mjs. Do not edit.\n"
        "namespace effetune::generated {\n\n"
        "struct %sParams {\n%s\n"
        "  static constexpr std::uint32_t kHash = 0x%08xu;\n"
        "  static constexpr std::uint32_t kFloatCount = %du;\n"
        "};\n}\n" % (type_name, body, hash_value, float_count))


class MiniVendor:
    """gen_catalog が読む木を一時フォルダに作り、モジュールの定数をそこへ向ける。"""

    def __init__(self, root):
        self.root = root
        self.vendor = root / "Vendor" / "effetune"
        write(root / "Sources/EffeTuneLive/Generated/UpstreamVersion.swift",
              'let ETUpstreamVersion = "9.9.9"\n')
        write(root / "Sources/EffeTuneLive/DSP/ETParamCoding.swift",
              'enum ETAllowedValues {\n    static let table: [String: [Float]] = [\n'
              '        "GainPlugin.os": [1, 2, 4],\n    ]\n}\n\nenum Other {}\n')

    def plugin(self, category, folder, type_name, fields, members, js="", hash_value=0x1234abcd,
               float_count=None, with_header=True):
        write(self.vendor / "dsp/plugins" / category / folder / "params.json",
              json.dumps({"type": type_name, "fields": fields}))
        if with_header:
            write(self.vendor / "dsp/generated/cpp" / (type_name + "Params.h"),
                  header(type_name, members, hash_value, float_count))
        if js:
            write(self.vendor / "plugins" / category / (folder + ".js"), js)

    def bind(self, gc):
        gc.ROOT = self.root
        gc.VENDOR = self.vendor
        gc.DSP = self.vendor / "dsp"
        gc.JS_PLUGINS = self.vendor / "plugins"
        gc.OUT = self.root / "Sources/EffeTuneLive/Generated/EffectCatalog.swift"
        gc.CHAIN = self.root / "chain"
        gc.UPSTREAM_VERSION = self.root / "Sources/EffeTuneLive/Generated/UpstreamVersion.swift"
        gc.PARAM_CODING = self.root / "Sources/EffeTuneLive/DSP/ETParamCoding.swift"
        gc.CHAIN_UNSUPPORTED = {}   # 本物の表の型は小さな Vendor に居ない
        return gc


