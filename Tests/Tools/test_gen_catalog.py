@unittest.skipUnless(have_git(), "git が無い")
class VendorPinTests(unittest.TestCase):
    """固定した版（gitlink）と Vendor の HEAD を比べる検査。一時リポジトリで確かめる。"""

    def setUp(self):
        self.gc = load_tool("gen_catalog")

    def make(self, tmp):
        env = hermetic_git_env(tmp)
        sup = tmp / "super"
        vendor = sup / "Vendor" / "effetune"
        vendor.mkdir(parents=True)
        git(vendor, "init", "-q", "-b", "main", env=env)
        write(vendor / "dsp/README", "old\n")
        git(vendor, "add", ".", env=env)
        git(vendor, "commit", "-q", "-m", "old", env=env)
        git(vendor, "tag", "dsp-v0.10.0", env=env)
        old = git(vendor, "rev-parse", "HEAD", env=env)
        write(vendor / "dsp/README", "new\n")
        git(vendor, "commit", "-q", "-am", "new", env=env)
        git(vendor, "tag", "dsp-v0.11.0", env=env)
        new = git(vendor, "rev-parse", "HEAD", env=env)
        git(sup, "init", "-q", "-b", "main", env=env)
        write(sup / "README.md", "x\n")
        git(sup, "add", "README.md", env=env)
        git(sup, "update-index", "--add", "--cacheinfo", "160000,%s,Vendor/effetune" % new, env=env)
        git(sup, "commit", "-q", "-m", "pin", env=env)
        self.gc.ROOT = sup
        self.gc.VENDOR = vendor
        return env, sup, vendor, old, new

    def test_vendor_pin_rejects_old_tag(self):
        with TempDir() as tmp:
            env, sup, vendor, old, new = self.make(tmp)
            with env_patch(**{k: env[k] for k in ("GIT_CONFIG_GLOBAL", "GIT_CONFIG_NOSYSTEM")}):
                git(vendor, "checkout", "-q", old, env=env)
                self.assertTrue(self.gc.vendor_is_checkout())
                with self.assertRaises(SystemExit) as cm:
                    self.gc.check_vendor_pin()
                self.assertIn(old[:8], str(cm.exception.code))
                git(vendor, "checkout", "-q", new, env=env)
                self.gc.check_vendor_pin()  # 固定と同じなら通る
                self.assertEqual(self.gc.dsp_version(True), "0.11.0")

    def test_staged_gitlink_accepted(self):
        # 上流へ追従するときは Vendor を進めて git add してから走らせる。index の gitlink も固定として受ける。
        with TempDir() as tmp:
            env, sup, vendor, old, new = self.make(tmp)
            with env_patch(**{k: env[k] for k in ("GIT_CONFIG_GLOBAL", "GIT_CONFIG_NOSYSTEM")}):
                git(vendor, "checkout", "-q", old, env=env)
                git(sup, "update-index", "--cacheinfo", "160000,%s,Vendor/effetune" % old, env=env)
                self.gc.check_vendor_pin()
                self.assertEqual(self.gc.dsp_version(True), "0.10.0")

    def test_between_tags_uses_previous_tag(self):
        with TempDir() as tmp:
            env, sup, vendor, old, new = self.make(tmp)
            with env_patch(**{k: env[k] for k in ("GIT_CONFIG_GLOBAL", "GIT_CONFIG_NOSYSTEM")}):
                write(vendor / "dsp/README", "newer\n")
                git(vendor, "commit", "-q", "-am", "newer", env=env)
                self.assertEqual(self.gc.dsp_version(True), "0.11.0")

    def test_no_git_fallback(self):
        # Mac へ送った木は git ではない。版は追跡してある UpstreamVersion.swift から取り、pin は見ない。
        with TempDir() as tmp:
            vendor = tmp / "copy" / "Vendor" / "effetune"
            vendor.mkdir(parents=True)
            uv = write(tmp / "copy/UpstreamVersion.swift", 'let ETUpstreamVersion = "0.11.0"\n')
            self.gc.VENDOR = vendor
            self.gc.ROOT = tmp / "copy"
            self.gc.UPSTREAM_VERSION = uv
            env = hermetic_git_env(tmp)
            with env_patch(GIT_CONFIG_GLOBAL=env["GIT_CONFIG_GLOBAL"], GIT_CONFIG_NOSYSTEM="1",
                           GIT_CEILING_DIRECTORIES=str(tmp)):
                self.assertFalse(self.gc.vendor_is_checkout())
                self.gc.check_vendor_pin()   # git が開けなければ何もしない
                self.assertEqual(self.gc.dsp_version(False), "0.11.0")


class ChainFolderTests(unittest.TestCase):
    def setUp(self):
        self.gc = load_tool("gen_catalog")

    def test_chain_folder_tampered(self):
        # 同じ版のフォルダを別のパラメータの形で上書きしない。
        with TempDir() as tmp:
            self.gc.CHAIN = tmp / "chain"
            write(tmp / "chain/v0.11.0/effects.json", json.dumps({"dsp": "0.11.0", "dspParams": "aaaa"}))
            with self.assertRaises(SystemExit) as cm:
                self.gc.check_chain_folder("0.11.0", "bbbb")
            self.assertIn("aaaa", str(cm.exception.code))
            self.gc.check_chain_folder("0.11.0", "aaaa")
            self.gc.check_chain_folder("0.12.0", "bbbb")  # 無い版は書いてよい

    def test_fingerprint_ignores_order_and_generator_changes(self):
        a = [{"type": "B", "hash": 2, "floatCount": 1}, {"type": "A", "hash": 1, "floatCount": 3}]
        b = list(reversed(a))
        self.assertEqual(self.gc.dsp_params_fingerprint(a), self.gc.dsp_params_fingerprint(b))
        c = [dict(a[0], floatCount=2), a[1]]
        self.assertNotEqual(self.gc.dsp_params_fingerprint(a), self.gc.dsp_params_fingerprint(c))


